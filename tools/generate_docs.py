"""Generate the static browser roadmap module from its JSON source; no Node."""
from pathlib import Path
import argparse,json

ROOT=Path(__file__).resolve().parents[1]


def source(root=ROOT):
    data=json.loads((root/'docs/tasks-data.json').read_text(encoding='utf-8'))
    if data.get('schema_version')!=1:raise ValueError('Unsupported roadmap schema')
    numbers=[record['number'] for record in data['post100Tasks']]
    if len(numbers)!=len(set(numbers)):raise ValueError('Duplicate authoritative task number')
    return data


def render(data):
    result=['// Generated by tools/generate_docs.py from tasks-data.json.\n// Static browser ES module; generation requires Python only.\n']
    for key in ['foundationTaskGroups','post100Tasks','roadmapRules','recommendedOrder']:
        result.append('export const '+key+' = '+json.dumps(data[key],indent=2,ensure_ascii=False)+';\n')
    result.append('''let nextNumber = 1;
export const foundationTasks = foundationTaskGroups.flatMap(group => group.tasks.map(([title, description]) => {
  const number = nextNumber++;
  return {number, title, description, category: group.name, status: number <= 100 ? "completed" : "planned"};
}));
''')
    result.append('const futureGroups = '+json.dumps(data['futureGroups'],indent=2,ensure_ascii=False)+';\n')
    result.append('''export const taskGroups = [...foundationTaskGroups, {
  name: "Post-100 Usable Command Center", range: "101-130",
  tasks: post100Tasks.filter(task => task.number <= 130).map(({title, description}) => [title, description]),
}, ...futureGroups.map(({name, range}) => ({name, range,
  tasks: post100Tasks.filter(task => task.category === name).map(({title, description}) => [title, description])}))];
export const tasks = [...foundationTasks, ...post100Tasks];
export const nextTask = recommendedOrder.map(({number}) => post100Tasks.find(task => task.number === number))
  .find(task => task?.status === "planned") ?? post100Tasks.find(task => task.status === "planned");
''')
    return '\n'.join(result)


def generate(root=ROOT,*,check=False):
    expected=render(source(root));path=root/'docs/tasks-data.mjs'
    if check:
        if not path.exists() or path.read_text(encoding='utf-8')!=expected:
            raise ValueError('Static roadmap is stale; run python tools/generate_docs.py')
    else:path.write_text(expected,encoding='utf-8')


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    generate(check=args.check);print('Static roadmap matches its JSON source.' if args.check else 'Generated the static roadmap from JSON using Python.')
